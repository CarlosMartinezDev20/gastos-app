#!/usr/bin/env bash
# Installs the alternate launcher icons (one per accent but Lima, the default)
# from branding/svg/accent-icons/ into the Android and iOS projects. Run from
# anywhere after build_kit.py; flutter_launcher_icons doesn't touch these files.
#   Android: mipmap-*/ic_launcher_<accent>.png (legacy), drawable-*/
#            ic_launcher_foreground_<accent>.png + mipmap-anydpi-v26/
#            ic_launcher_<accent>.xml (adaptive; background and monochrome
#            shared with the default icon). Used by the activity-aliases in
#            AndroidManifest.xml.
#   iOS:     Assets.xcassets/AppIcon-<Accent>.appiconset (single 1024 size),
#            listed in ASSETCATALOG_COMPILER_ALTERNATE_APP_ICON_NAMES.
set -euo pipefail
cd "$(dirname "$0")"
S=svg/accent-icons
RES=../android/app/src/main/res
XC=../ios/Runner/Assets.xcassets

declare -A LEGACY=([mdpi]=48 [hdpi]=72 [xhdpi]=96 [xxhdpi]=144 [xxxhdpi]=192)
declare -A FOREGROUND=([mdpi]=108 [hdpi]=162 [xhdpi]=216 [xxhdpi]=324 [xxxhdpi]=432)

for name in Menta Cielo Violeta Ambar; do
  key=${name,,}
  for d in "${!LEGACY[@]}"; do
    rsvg-convert -w "${LEGACY[$d]}" -h "${LEGACY[$d]}" "$S/$key-app-icon-rounded.svg" \
      -o "$RES/mipmap-$d/ic_launcher_$key.png"
    rsvg-convert -w "${FOREGROUND[$d]}" -h "${FOREGROUND[$d]}" "$S/$key-android-foreground.svg" \
      -o "$RES/drawable-$d/ic_launcher_foreground_$key.png"
  done
  cat > "$RES/mipmap-anydpi-v26/ic_launcher_$key.xml" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by branding/accent_icons.sh: the «$name» accent's launcher icon. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
  <background android:drawable="@drawable/ic_launcher_background"/>
  <foreground android:drawable="@drawable/ic_launcher_foreground_$key"/>
  <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
EOF

  set_dir="$XC/AppIcon-$name.appiconset"
  mkdir -p "$set_dir"
  # iOS icons can't have an alpha channel (App Store): flatten on the ink background.
  rsvg-convert -w 1024 -h 1024 -b '#1C1C1E' "$S/$key-app-icon.svg" \
    | magick png:- -alpha off "$set_dir/Icon-1024.png"
  cat > "$set_dir/Contents.json" <<EOF
{
  "images" : [
    {
      "filename" : "Icon-1024.png",
      "idiom" : "universal",
      "platform" : "ios",
      "size" : "1024x1024"
    }
  ],
  "info" : {
    "author" : "xcode",
    "version" : 1
  }
}
EOF
done
echo "Accent icons installed."
